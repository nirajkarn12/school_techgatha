/*
|--------------------------------------------------------------------------
| HELPER: CREATE IMAGE FILENAME
|--------------------------------------------------------------------------
|
| Example:
| Rumi + 5 = rumi_5.jpg
| Rumi Shrestha + 5 = rumi_shrestha_5.jpg
|
*/
function createBirthdayImageName($studentName, $className, $extension = 'jpg')
{
    $studentName = strtolower(trim($studentName));
    $className   = strtolower(trim($className));

    // Remove "class" from class name if present.
    // Example: Class 5 -> 5
    $className = preg_replace('/^class[\s_-]*/i', '', $className);

    // Convert spaces and special characters to underscore.
    $studentName = preg_replace('/[^a-z0-9]+/i', '_', $studentName);
    $className   = preg_replace('/[^a-z0-9]+/i', '_', $className);

    $studentName = trim($studentName, '_');
    $className   = trim($className, '_');

    $extension = strtolower($extension);
    if (!in_array($extension, ['jpg', 'jpeg', 'png', 'gif', 'webp'], true)) {
        $extension = 'jpg';
    }

    return $studentName . '_' . $className . '.' . $extension;
}

/*
|--------------------------------------------------------------------------
| HELPER: NORMALIZE IMAGE KEY
|--------------------------------------------------------------------------
|
| Rumi_5.jpg
| rumi_5.JPG
|
| Both become:
| rumi_5
|
*/
function normalizeBirthdayImageKey($filename)
{
    $filename = pathinfo($filename, PATHINFO_FILENAME);

    $filename = strtolower(trim($filename));

    $filename = preg_replace('/[^a-z0-9]+/i', '_', $filename);

    return trim($filename, '_');
}

