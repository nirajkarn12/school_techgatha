if (isset($_GET['export_csv'])) {

    // Remove all HTML already generated by header.php.
    ob_end_clean();

    $filename = 'birthday_students_' . date('Y-m-d_H-i-s') . '.csv';

    header('Content-Type: text/csv; charset=UTF-8');
    header('Content-Disposition: attachment; filename="' . $filename . '"');
    header('Pragma: no-cache');
    header('Expires: 0');

    $output = fopen('php://output', 'w');

    // UTF-8 BOM for Excel compatibility.
    fwrite($output, "\xEF\xBB\xBF");

    /*
    |--------------------------------------------------------------------------
    | CSV HEADER
    |--------------------------------------------------------------------------
    */

    fputcsv($output, [
        'student_name',
        'class',
        'birthday',
        'image',
        'template',
        'status'
    ]);

    $exportStmt = $pdo->prepare("
        SELECT
            s.name AS student_name,
            s.class_name AS class,
            s.birthday_date AS birthday,
            s.student_image AS image,
            'Default Birthday Card' AS template,
            'Active' AS status
        FROM tbl_birthday_student s
        LEFT JOIN tbl_birthday_template t
            ON t.id = s.template_id
        ORDER BY
            s.sort_order ASC,
            s.id DESC
    ");

    $exportStmt->execute();

