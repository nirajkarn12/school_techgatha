if ($_SERVER['REQUEST_METHOD'] === 'POST' && isset($_POST['upload_csv'])) {

    if (
        !isset($_FILES['birthday_csv']) ||
        $_FILES['birthday_csv']['error'] !== UPLOAD_ERR_OK
    ) {

        $error_message = 'Please select a valid CSV file.';

    } else {

        $file = $_FILES['birthday_csv'];

        /*
        |--------------------------------------------------------------------------
        | Check CSV Extension
        |--------------------------------------------------------------------------
        */

        $extension = strtolower(
            pathinfo($file['name'], PATHINFO_EXTENSION)
        );

        if ($extension !== 'csv') {

            $error_message = 'Only CSV files are allowed.';

        } else {

            $handle = fopen($file['tmp_name'], 'r');

            if ($handle === false) {

                $error_message = 'Unable to read the CSV file.';

            } else {

                /*
                |--------------------------------------------------------------------------
                | Find Default Birthday Card Template
                |--------------------------------------------------------------------------
                */

                $templateStmt = $pdo->prepare("
                    SELECT id
                    FROM tbl_birthday_template
                    WHERE LOWER(TRIM(title)) = LOWER(TRIM(?))
                    LIMIT 1
                ");

                $templateStmt->execute([
                    'Default Birthday Card'
                ]);

                $defaultTemplate = $templateStmt->fetch(PDO::FETCH_ASSOC);

                if (!$defaultTemplate) {

                    fclose($handle);

                    $error_message =
                        'Default Birthday Card template was not found. Please create the template first.';

                } else {

                    $templateId = (int)$defaultTemplate['id'];

                    /*
                    |--------------------------------------------------------------------------
                    | Read CSV Header
                    |--------------------------------------------------------------------------
                    */

                    $header = fgetcsv($handle);

                    if (!$header) {

                        fclose($handle);

                        $error_message = 'The CSV file is empty.';

                    } else {

                        /*
                        |--------------------------------------------------------------------------
                        | Remove UTF-8 BOM
                        |--------------------------------------------------------------------------
                        */

                        $header[0] = preg_replace(
                            '/^\xEF\xBB\xBF/',
                            '',
                            $header[0]
                        );

                        /*
                        |--------------------------------------------------------------------------
                        | Normalize Header Names
                        |--------------------------------------------------------------------------
                        */

                        $header = array_map(function ($value) {

                            return strtolower(trim($value));

                        }, $header);

                        /*
                        |--------------------------------------------------------------------------
                        | Required Columns
                        |--------------------------------------------------------------------------
                        |
                        | IMAGE IS NOT REQUIRED.
                        |
                        | PHP automatically creates:
                        |
                        | Rumi + 5 = rumi_5.jpg
                        |
                        */

                        $requiredColumns = [
                            'student_name',
                            'class',
                            'birthday',
                            'template',
                            'status'
                        ];

                        $missingColumns = [];

                        foreach ($requiredColumns as $column) {

                            if (!in_array($column, $header, true)) {

                                $missingColumns[] = $column;
                            }
                        }

                        if (!empty($missingColumns)) {

                            fclose($handle);

                            $error_message =
                                'Missing CSV column(s): ' .
                                implode(', ', $missingColumns);

                        } else {

                            /*
                            |--------------------------------------------------------------------------
                            | Get Column Positions
                            |--------------------------------------------------------------------------
                            */

                            $studentNameIndex =
                                array_search(
                                    'student_name',
                                    $header,
                                    true
                                );

                            $classIndex =
                                array_search(
                                    'class',
                                    $header,
                                    true
                                );

                            $birthdayIndex =
                                array_search(
                                    'birthday',
                                    $header,
                                    true
                                );

                            $templateIndex =
                                array_search(
                                    'template',
                                    $header,
                                    true
                                );

                            $statusIndex =
                                array_search(
                                    'status',
                                    $header,
                                    true
                                );

                            // The image column is optional for older CSV files.
                            $imageIndex = array_search('image', $header, true);
                            if ($imageIndex === false) {
                                $imageIndex = array_search('student_image', $header, true);
                            }

                            $imported = 0;
                            $updated = 0;
                            $failed = 0;

                            $errors = [];

                            $rowNumber = 1;

                            try {

                                $pdo->beginTransaction();

                                /*
                                |--------------------------------------------------------------------------
                                | Find Existing Student By Name And Class
                                |--------------------------------------------------------------------------
                                */

                                $findByClassStmt = $pdo->prepare("
                                    SELECT id
                                    FROM tbl_birthday_student
                                                                        WHERE LOWER(TRIM(name)) = LOWER(TRIM(?))
                                                                            AND LOWER(TRIM(class_name)) = LOWER(TRIM(?))
                                    ORDER BY id ASC
                                    LIMIT 1
                                ");

                                /*
                                |--------------------------------------------------------------------------
                                | INSERT
                                |--------------------------------------------------------------------------
                                */

                                $insertStmt = $pdo->prepare("
                                    INSERT INTO tbl_birthday_student
                                    (
                                        name,
                                        class_name,
                                        birthday_date,
                                        student_image,
                                        template_id,
                                        status
                                    )
                                    VALUES
                                    (
                                        ?,
                                        ?,
                                        ?,
                                        ?,
                                        ?,
                                        ?
                                    )
                                ");

                                /*
                                |--------------------------------------------------------------------------
                                | UPDATE
                                |--------------------------------------------------------------------------
                                */

                                $updateStmt = $pdo->prepare("
                                    UPDATE tbl_birthday_student
                                    SET
                                        name = ?,
                                        class_name = ?,
                                        birthday_date = ?,
                                        student_image = ?,
                                        template_id = ?,
                                        status = ?
                                    WHERE id = ?
                                ");

                                /*
                                |--------------------------------------------------------------------------
                                | Read CSV Rows
                                |--------------------------------------------------------------------------
                                */

                                while (($data = fgetcsv($handle)) !== false) {

                                    $rowNumber++;

                                    /*
                                    |--------------------------------------------------------------------------
                                    | Skip Empty Rows
                                    |--------------------------------------------------------------------------
                                    */

                                    if (
                                        count($data) === 1 &&
                                        trim($data[0]) === ''
                                    ) {

                                        continue;
                                    }

                                    /*
                                    |--------------------------------------------------------------------------
                                    | Get Values
                                    |--------------------------------------------------------------------------
                                    */

                                    $studentName =
                                        trim(
                                            $data[$studentNameIndex] ?? ''
                                        );

                                    $className =
                                        trim(
                                            $data[$classIndex] ?? ''
                                        );

                                    $birthday =
                                        trim(
                                            $data[$birthdayIndex] ?? ''
                                        );

                                    $template =
                                        trim(
                                            $data[$templateIndex] ?? ''
                                        );

                                    $status =
                                        trim(
                                            $data[$statusIndex] ?? ''
                                        );

                                    /*
                                    |--------------------------------------------------------------------------
                                    | Generate Student Image Filename
                                    |--------------------------------------------------------------------------
                                    |
                                    | Rumi + 5
                                    |
                                    | becomes:
                                    |
                                    | rumi_5.jpg
                                    |
                                    */

                                    // Keep the CSV image extension when valid, but always
                                    // use the predictable name_class filename.
                                    $csvImage = $imageIndex !== false
                                        ? basename(trim($data[$imageIndex] ?? ''))
                                        : '';
                                    $imageExtension = strtolower(
                                        pathinfo($csvImage, PATHINFO_EXTENSION)
                                    );
                                    if (!in_array($imageExtension, ['jpg', 'jpeg', 'png', 'gif', 'webp'], true)) {
                                        $imageExtension = 'jpg';
                                    }
                                    $studentImage = createBirthdayImageName(
                                        $studentName,
                                        $className,
                                        $imageExtension
                                    );

                                    /*
                                    |--------------------------------------------------------------------------
                                    | Validate Student Name
                                    |--------------------------------------------------------------------------
                                    */

                                    if ($studentName === '') {

                                        $failed++;

                                        $errors[] =
                                            "Row {$rowNumber}: Student name is required.";

                                        continue;
                                    }

                                    /*
                                    |--------------------------------------------------------------------------
                                    | Validate Class
                                    |--------------------------------------------------------------------------
                                    */

                                    if ($className === '') {

                                        $failed++;

                                        $errors[] =
                                            "Row {$rowNumber}: Class is required.";

                                        continue;
                                    }

                                    /*
                                    |--------------------------------------------------------------------------
                                    | Validate Birthday
                                    |--------------------------------------------------------------------------
                                    */

                                    if ($birthday !== '') {

                                        $dateObject =
                                            DateTime::createFromFormat(
                                                'Y-m-d',
                                                $birthday
                                            );

                                        if (
                                            !$dateObject ||
                                            $dateObject->format('Y-m-d') !== $birthday
                                        ) {

                                            $failed++;

                                            $errors[] =
                                                "Row {$rowNumber}: Invalid birthday '{$birthday}'. Use YYYY-MM-DD.";

                                            continue;
                                        }
                                    }

                                    /*
                                    |--------------------------------------------------------------------------
                                    | Template MUST be Default Birthday Card
                                    |--------------------------------------------------------------------------
                                    */

                                    if (
                                        strcasecmp(
                                            $template,
                                            'Default Birthday Card'
                                        ) !== 0
                                    ) {

                                        $failed++;

                                        $errors[] =
                                            "Row {$rowNumber}: Template must be 'Default Birthday Card'.";

                                        continue;
                                    }

                                    /*
                                    |--------------------------------------------------------------------------
                                    | Status MUST be Active
                                    |--------------------------------------------------------------------------
                                    */

                                    if (
                                        strcasecmp(
                                            $status,
                                            'Active'
                                        ) !== 0
                                    ) {

                                        $failed++;

                                        $errors[] =
                                            "Row {$rowNumber}: Status must be 'Active'.";

                                        continue;
                                    }

                                    /*
                                    |--------------------------------------------------------------------------
                                    | Find Existing Student
                                    |--------------------------------------------------------------------------
                                    */

                                    $findByClassStmt->execute([
                                        $studentName,
                                        $className
                                    ]);

                                    $existingStudent =
                                        $findByClassStmt->fetch(
                                            PDO::FETCH_ASSOC
                                        );

                                    /*
                                    |--------------------------------------------------------------------------
                                    | UPDATE EXISTING
                                    |--------------------------------------------------------------------------
                                    */

                                    if ($existingStudent) {

                                        $updateStmt->execute([
                                            $studentName,
                                            $className,
                                            $birthday,
                                            $studentImage,
                                            $templateId,
                                            'Active',
                                            (int)$existingStudent['id']
                                        ]);

                                        $updated++;

                                    } else {

                                        /*
                                        |--------------------------------------------------------------------------
                                        | INSERT NEW
                                        |--------------------------------------------------------------------------
                                        */

                                        $insertStmt->execute([
                                            $studentName,
                                            $className,
                                            $birthday,
                                            $studentImage,
                                            $templateId,
                                            'Active'
                                        ]);

                                        $imported++;
                                    }
                                }

                                fclose($handle);

                                $pdo->commit();

                                /*
                                |--------------------------------------------------------------------------
                                | Success Message
                                |--------------------------------------------------------------------------
                                */

                                if ($imported > 0 || $updated > 0) {

                                    $messageParts = [];

                                    if ($imported > 0) {

                                        $messageParts[] =
                                            "{$imported} birthday student(s) added";
                                    }

                                    if ($updated > 0) {

                                        $messageParts[] =
                                            "{$updated} birthday student(s) updated";
                                    }

                                    $success_message =
                                        implode('. ', $messageParts) . '.';

                                    if ($failed > 0) {

                                        $success_message .=
                                            " {$failed} row(s) were skipped.";
                                    }

                                } else {

                                    $error_message =
                                        'No students were imported or updated.';

                                    if (!empty($errors)) {

                                        $error_message .=
                                            ' Please check the errors below.';
                                    }
                                }

                            } catch (Exception $e) {

                                if ($pdo->inTransaction()) {

                                    $pdo->rollBack();
                                }

                                fclose($handle);

                                $error_message =
                                    'CSV import failed: ' .
                                    $e->getMessage();
                            }

                            /*
                            |--------------------------------------------------------------------------
                            | Display Row Errors
                            |--------------------------------------------------------------------------
                            */

                            if (!empty($errors)) {

                                $error_message .=
                                    '<br><br><strong>Import Errors:</strong><br>';

                                $error_message .=
                                    implode(
                                        '<br>',
                                        array_map(
                                            'htmlspecialchars',
                                            $errors
                                        )
                                    );
                            }
                        }
                    }
                }
            }
        }
    }
}

/*
|--------------------------------------------------------------------------
| BULK IMAGE UPLOAD
|--------------------------------------------------------------------------
|
| Select multiple images at once.
|
| Example:
|
| rumi_5.jpg
| sita_6.jpg
| ram_7.jpg
|
| The system finds the matching student and updates student_image.
|
*/

if ($_SERVER['REQUEST_METHOD'] === 'POST' && isset($_POST['upload_images'])) {

    if (
        !isset($_FILES['birthday_images']) ||
        !isset($_FILES['birthday_images']['name']) ||
        !is_array($_FILES['birthday_images']['name'])
    ) {

        $error_message = 'Please select one or more image files.';

    } else {

        $uploadedCount = 0;
        $updatedCount = 0;
        $skippedCount = 0;

        $imageErrors = [];

        /*
        |--------------------------------------------------------------------------
        | Allowed Image Types
        |--------------------------------------------------------------------------
        */

        $allowedExtensions = [
            'jpg',
            'jpeg',
            'gif',
            'png',
            'webp'
        ];

        /*
        |--------------------------------------------------------------------------
        | Prepare Student Records
        |--------------------------------------------------------------------------
        */

        $studentStmt = $pdo->prepare("
            SELECT
                id,
                name,
                class_name
            FROM tbl_birthday_student
        ");

        $studentStmt->execute();

        $students = $studentStmt->fetchAll(PDO::FETCH_ASSOC);

        /*
        |--------------------------------------------------------------------------
        | Build Student Lookup
        |--------------------------------------------------------------------------
        |
        | Example:
        |
        | Rumi + 5
        |
        | becomes:
        |
        | rumi_5
        |
        */

        $studentLookup = [];

        foreach ($students as $student) {

            $expectedFilename =
                createBirthdayImageName(
                    $student['name'],
                    $student['class_name']
                );

            $lookupKey =
                normalizeBirthdayImageKey(
                    $expectedFilename
                );

            $studentLookup[$lookupKey] = [
                'id' => (int)$student['id'],
                'name' => $student['name'],
                'class_name' => $student['class_name'],
                'filename' => $expectedFilename
            ];
        }

        /*
        |--------------------------------------------------------------------------
        | Process Every Selected Image
        |--------------------------------------------------------------------------
        */

        $totalImages =
            count($_FILES['birthday_images']['name']);

        for ($i = 0; $i < $totalImages; $i++) {

            $originalName =
                $_FILES['birthday_images']['name'][$i];

            $tmpName =
                $_FILES['birthday_images']['tmp_name'][$i];

            $uploadError =
                $_FILES['birthday_images']['error'][$i];

            /*
            |--------------------------------------------------------------------------
            | Check Upload Error
            |--------------------------------------------------------------------------
            */

            if ($uploadError !== UPLOAD_ERR_OK) {

                $skippedCount++;

                $imageErrors[] =
                    "Image '{$originalName}' could not be uploaded.";

                continue;
            }

            /*
            |--------------------------------------------------------------------------
            | Check Extension
            |--------------------------------------------------------------------------
            */

            $extension =
                strtolower(
                    pathinfo(
                        $originalName,
                        PATHINFO_EXTENSION
                    )
                );

            if (!in_array($extension, $allowedExtensions, true)) {

                $skippedCount++;

                $imageErrors[] =
                    "Image '{$originalName}' is not a supported image.";

                continue;
            }

            /*
            |--------------------------------------------------------------------------
            | Verify Actual Image
            |--------------------------------------------------------------------------
            */

            $imageInfo = @getimagesize($tmpName);

            if ($imageInfo === false) {

                $skippedCount++;

                $imageErrors[] =
                    "Image '{$originalName}' is not a valid image.";

                continue;
            }

            /*
            |--------------------------------------------------------------------------
            | Find Student By Filename
            |--------------------------------------------------------------------------
            |
            | rumi_5.jpg
            |
            | becomes:
            |
            | rumi_5
            |
            */

            $imageKey =
                normalizeBirthdayImageKey(
                    $originalName
                );

            if (!isset($studentLookup[$imageKey])) {

                $skippedCount++;

                $imageErrors[] =
                    "Image '{$originalName}' does not match any student. Expected filename format: studentname_class.jpg";

                continue;
            }

            $student =
                $studentLookup[$imageKey];

            /*
            |--------------------------------------------------------------------------
            | Always Save With Standard Filename
            |--------------------------------------------------------------------------
            |
            | Even if user uploads:
            |
            | RUMI_5.JPG
            |
            | it will be saved as:
            |
            | rumi_5.jpg
            |
            */

            $destinationFilename =
                createBirthdayImageName(
                    $student['name'],
                    $student['class_name'],
                    $extension
                );

            /*
            |--------------------------------------------------------------------------
            | Destination Path
            |--------------------------------------------------------------------------
            */

            $destinationPath =
                adminUploadsPath(
                    $destinationFilename
                );

            $destinationDirectory =
                dirname($destinationPath);

            /*
            |--------------------------------------------------------------------------
            | Create Directory If Needed
            |--------------------------------------------------------------------------
            */

            if (!is_dir($destinationDirectory)) {

                if (
                    !mkdir(
                        $destinationDirectory,
                        0755,
                        true
                    )
                ) {

                    $skippedCount++;

                    $imageErrors[] =
                        "Unable to create upload directory for '{$originalName}'.";

                    continue;
                }
            }

            /*
            |--------------------------------------------------------------------------
            | Move Image
            |--------------------------------------------------------------------------
            */

            if (
                !move_uploaded_file(
                    $tmpName,
                    $destinationPath
                )
            ) {

                $skippedCount++;

                $imageErrors[] =
                    "Unable to save image '{$originalName}'.";

                continue;
            }

            /*
            |--------------------------------------------------------------------------
            | Update Database
            |--------------------------------------------------------------------------
            */

            try {

                $imageUpdateStmt = $pdo->prepare("
                    UPDATE tbl_birthday_student
                    SET student_image = ?
                    WHERE id = ?
                ");

                $imageUpdateStmt->execute([
                    $destinationFilename,
                    $student['id']
                ]);

                $updatedCount++;
                $uploadedCount++;

            } catch (Exception $e) {

                /*
                |--------------------------------------------------------------------------
                | Remove Uploaded File If Database Update Fails
                |--------------------------------------------------------------------------
                */

                if (is_file($destinationPath)) {

                    @unlink($destinationPath);
                }

                $skippedCount++;

                $imageErrors[] =
                    "Database update failed for '{$originalName}': " .
                    $e->getMessage();
            }
        }

        /*
        |--------------------------------------------------------------------------
        | Bulk Image Upload Message
        |--------------------------------------------------------------------------
        */

        if ($updatedCount > 0) {

            $success_message =
                "{$updatedCount} student image(s) uploaded and matched successfully.";

            if ($skippedCount > 0) {

                $success_message .=
                    " {$skippedCount} image(s) were skipped.";
            }

        } else {

            $error_message =
                'No student images were uploaded.';

            if (!empty($imageErrors)) {

                $error_message .=
                    '<br><br><strong>Image Upload Errors:</strong><br>' .
                    implode(
                        '<br>',
                        array_map(
                            'htmlspecialchars',
                            $imageErrors
                        )
                    );
            }
        }

        /*
        |--------------------------------------------------------------------------
        | Display Image Errors Even When Some Images Succeeded
        |--------------------------------------------------------------------------
        */

        if (
            $updatedCount > 0 &&
            !empty($imageErrors)
        ) {

            $error_message =
                '<strong>Skipped Images:</strong><br>' .
                implode(
                    '<br>',
                    array_map(
                        'htmlspecialchars',
                        $imageErrors
                    )
                );
        }
    }
}

